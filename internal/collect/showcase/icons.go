// Showcase favicons are generated in memory (no files, no network) so demo
// screenshots show directory-discovered icons. Keyed by working directory.
type demoIcon struct {
	rel  string
	data []byte
}

var (
	demoIconsOnce sync.Once
	demoIcons     map[string]demoIcon
)

func loadDemoIcons() map[string]demoIcon {
	demoIconsOnce.Do(func() {
		demoIcons = map[string]demoIcon{
			"/srv/apps/nova-core":     {rel: "web/public/favicon.svg", data: []byte(novaSVG)},
			"/srv/apps/analytics-hub": {rel: "frontend/public/apple-touch-icon.png", data: analyticsPNG()},
		}
	})
	return demoIcons
}

// novaSVG is a four-pointed star on a rounded square.
const novaSVG = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">` +
	`<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">` +
	`<stop offset="0" stop-color="#6d5dfc"/><stop offset="1" stop-color="#22c3ee"/></linearGradient></defs>` +
	`<rect width="64" height="64" rx="14" fill="url(#g)"/>` +
	`<path d="M32 9 L37 27 L55 32 L37 37 L32 55 L27 37 L9 32 L27 27 Z" fill="#ffffff"/>` +
	`<circle cx="47" cy="17" r="3.5" fill="#ffffff" fill-opacity="0.8"/></svg>`

// analyticsPNG draws three rising bars on an amber tile (64x64).
func analyticsPNG() []byte {
	const n = 64
	img := image.NewNRGBA(image.Rect(0, 0, n, n))
	bg := color.NRGBA{R: 0xf5, G: 0x9e, B: 0x0b, A: 0xff}
	bar := color.NRGBA{R: 0x1c, G: 0x19, B: 0x17, A: 0xff}
	for y := range n {
		for x := range n {
			// Rounded corners (radius 12).
			if inCorner(x, y, n, 12) {
				continue
			}
			img.SetNRGBA(x, y, bg)
		}
	}
	bars := []struct{ x0, top int }{{14, 36}, {28, 24}, {42, 12}}
	for _, b := range bars {
		for y := b.top; y < 52; y++ {
			for x := b.x0; x < b.x0+9; x++ {
				img.SetNRGBA(x, y, bar)
			}
		}
	}
	var buf bytes.Buffer
	enc := png.Encoder{CompressionLevel: png.BestCompression}
	if err := enc.Encode(&buf, img); err != nil {
		return nil
	}
	return buf.Bytes()
}

func inCorner(x, y, n, r int) bool {
	cx, cy := -1, -1
	switch {
	case x < r && y < r:
		cx, cy = r, r
	case x >= n-r && y < r:
		cx, cy = n-r-1, r
	case x < r && y >= n-r:
		cx, cy = r, n-r-1
	case x >= n-r && y >= n-r:
		cx, cy = n-r-1, n-r-1
	default:
		return false
	}
	dx, dy := x-cx, y-cy
	return dx*dx+dy*dy > r*r
}

// DirIcon implements service.DirIconSource with generated demo icons.
func (p *Provider) DirIcon(workingDir string) (favicon.DirRef, bool) {
	ic, ok := loadDemoIcons()[workingDir]
	if !ok || len(ic.data) == 0 {
		return favicon.DirRef{}, false
	}
	sum := sha256.Sum256(ic.data)
	return favicon.DirRef{WorkingDir: workingDir, RelPath: ic.rel, SHA256: hex.EncodeToString(sum[:]), Size: len(ic.data), Generated: true}, true
}

// ReadDirIcon returns the generated bytes.
func (p *Provider) ReadDirIcon(_ context.Context, ref favicon.DirRef) ([]byte, error) {
	ic, ok := loadDemoIcons()[ref.WorkingDir]
	if !ok {
		return nil, errors.New("no demo icon")
	}
	return bytes.Clone(ic.data), nil
}
